const dictionaries: Record<LanguageCode, Record<string, string>> = {
  'en-US': enUS,
  'pt-BR': ptBR,
}

const I18nContext = createContext<I18nContextValue>({
  language: 'en-US',
  t: createTranslator('en-US'),
})

export function I18nProvider({ language, children }: { language: LanguageCode; children: ReactNode }) {
  return (
    <I18nContext.Provider value={{ language, t: createTranslator(language) }}>
      {children}
    </I18nContext.Provider>
  )
}

export function useI18n(): I18nContextValue {
  return useContext(I18nContext)
}

export function createTranslator(language: LanguageCode): Translator {
  const dictionary = dictionaries[language] ?? dictionaries['en-US']
  return (key, values) => interpolate(dictionary[key] ?? enUS[key] ?? key, values)
}

export function formatCompactNumber(value: number, language: LanguageCode): string {
  return Intl.NumberFormat(language, {
    notation: 'compact',
    maximumFractionDigits: 1,
  }).format(value)
}

export function formatStandardNumber(value: number, language: LanguageCode): string {
  return Intl.NumberFormat(language, {
    notation: value >= 100_000 ? 'compact' : 'standard',
    maximumFractionDigits: 1,
  }).format(value)
}

export function formatDateTime(value: number, language: LanguageCode): string {
  return new Intl.DateTimeFormat(language, {
    day: '2-digit',
    month: 'short',
    hour: '2-digit',
    minute: '2-digit',
  }).format(value)
}

function interpolate(text: string, values?: TranslationValues): string {
  if (!values) return text
  return text.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? ''))
}
